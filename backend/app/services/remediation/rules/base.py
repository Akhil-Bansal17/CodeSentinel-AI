"""Base definitions and abstract contracts for CodeSentinel AI Remediation Rules (Phase 7)."""

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Dict, List, Optional, Set


class RemediationRisk(str, Enum):
    """Risk classification of a remediation patch."""

    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"


class RemediationConfidence(str, Enum):
    """Confidence that the proposed patch correctly resolves the issue without regression."""

    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"


@dataclass
class RemediationCandidate:
    """A synthesized, candidate code replacement generated by a deterministic rule."""

    remediation_rule_id: str
    target_rule_id: str
    file_path: str
    start_line: int
    end_line: int
    original_snippet: str
    proposed_snippet: str
    rationale: str
    risk_level: RemediationRisk
    confidence: RemediationConfidence
    metadata: Dict[str, Any] = field(default_factory=dict)
    start_column: Optional[int] = None
    end_column: Optional[int] = None


@dataclass
class RemediationFeasibility:
    """Assessment of whether a finding can be safely remediated."""

    is_supported: bool
    remediation_rule_id: Optional[str] = None
    strategy_name: Optional[str] = None
    description: Optional[str] = None
    rationale: Optional[str] = None
    confidence: Optional[RemediationConfidence] = None
    risk_level: Optional[RemediationRisk] = None
    unsupported_reason: Optional[str] = None
    candidate: Optional[RemediationCandidate] = None
    requires_human_review: bool = True
    suggested_action: str = "MANUAL_REMEDIATION_REQUIRED"


class BaseRemediationRule(ABC):
    """Abstract base class for all deterministic remediation strategy rules."""

    @property
    @abstractmethod
    def rule_id(self) -> str:
        """Stable remediation strategy identifier (e.g. FIX-PYSEC001-LITERAL-EVAL)."""
        pass

    @property
    @abstractmethod
    def target_finding_rules(self) -> Set[str]:
        """Set of finding rule IDs supported by this strategy (e.g. {'PYSEC001'})."""
        pass

    @property
    @abstractmethod
    def name(self) -> str:
        """Human-readable strategy title."""
        pass

    @property
    @abstractmethod
    def description(self) -> str:
        """Description of the vulnerability or code pattern addressed."""
        pass

    @property
    @abstractmethod
    def transformation_strategy(self) -> str:
        """Summary of the code transformation performed."""
        pass

    @property
    @abstractmethod
    def risk_level(self) -> RemediationRisk:
        """Default risk level of this strategy."""
        pass

    @property
    @abstractmethod
    def default_confidence(self) -> RemediationConfidence:
        """Default confidence in this strategy."""
        pass

    @property
    @abstractmethod
    def applicable_languages(self) -> Set[str]:
        """Languages supported by this strategy."""
        pass

    @property
    @abstractmethod
    def preconditions(self) -> List[str]:
        """List of preconditions that must be verified before patch generation."""
        pass

    @property
    @abstractmethod
    def unsupported_cases(self) -> List[str]:
        """Explicitly unsupported patterns that must be rejected."""
        pass

    @property
    @abstractmethod
    def rationale(self) -> str:
        """Explanation of why this transformation is safer than the original code."""
        pass

    @abstractmethod
    def assess_feasibility(
        self,
        finding: Any,
        source_content: str,
    ) -> RemediationFeasibility:
        """Assess whether the specific finding in its source context can be remediated."""
        pass

    @abstractmethod
    def generate_candidate(
        self,
        finding: Any,
        source_content: str,
    ) -> Optional[RemediationCandidate]:
        """Generate a patch candidate if feasible."""
        pass
